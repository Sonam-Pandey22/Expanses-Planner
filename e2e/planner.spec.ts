import { test, expect } from '@playwright/test';
import mongoose from 'mongoose';

test('demo transaction CRUD, filtering, persistence, export, budgets, goals, and mobile navigation', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/dashboard');
  await expect(page.getByText('Your financial overview')).toBeVisible();
  await expect(page.locator('main[aria-busy="false"]')).toBeVisible();
  await expect(page.locator('.recharts-area-curve')).toHaveCount(2);
  await page.screenshot({ path: '.runtime/dashboard-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Add transaction', exact: true }).click();
  await page.getByRole('textbox', { name: 'Description', exact: true }).fill('Browser QA coffee');
  await page.getByRole('spinbutton', { name: 'Amount' }).fill('125.50');
  await page.getByRole('dialog').getByRole('button', { name: 'Add transaction' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'View all transactions' }).click();
  await page.getByRole('textbox', { name: 'Filter transactions' }).fill('Browser QA coffee');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.locator('tbody')).toContainText('125.5');
  await page.reload();
  await expect(page.locator('main[aria-busy="false"]')).toBeVisible();
  await page.getByRole('button', { name: 'View all transactions' }).click();
  await page.getByRole('textbox', { name: 'Filter transactions' }).fill('Browser QA coffee');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: 'Edit Browser QA coffee', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Amount' }).fill('150');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.locator('tbody')).toContainText('150');
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  expect((await downloaded).suggestedFilename()).toMatch(/expanse-.*\.csv/);
  await page.getByRole('button', { name: 'Delete Browser QA coffee', exact: true }).click();
  await page.getByRole('button', { name: 'Delete record', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(0);
  await page.getByRole('navigation').getByRole('button', { name: 'Budgets', exact: true }).click();
  await page.getByRole('button', { name: 'Create budget', exact: true }).first().click();
  await page.getByRole('dialog').getByRole('combobox', { name: 'Category', exact: true }).selectOption('Travel');
  await page.getByRole('spinbutton', { name: 'Monthly limit' }).fill('12000');
  await page.getByRole('button', { name: 'Save budget' }).click();
  await expect(page.locator('.budget-item').filter({ hasText: 'Travel' })).toContainText('12,000');
  await page.getByRole('navigation').getByRole('button', { name: 'Savings goals', exact: true }).click();
  await page.getByRole('button', { name: 'New goal', exact: true }).click();
  await page.getByRole('textbox', { name: 'What are you saving for?' }).fill('QA adventure');
  await page.getByRole('spinbutton', { name: 'Target amount' }).fill('10000');
  await page.getByRole('spinbutton', { name: 'Total saved' }).fill('2500');
  await page.getByRole('button', { name: 'Save goal' }).click();
  await expect(page.locator('.goal-card').filter({ hasText: 'QA adventure' })).toContainText('25%');
  await page.getByRole('navigation').getByRole('button', { name: 'Analytics', exact: true }).click();
  await expect(page.getByText('Your six-month story')).toBeVisible();
  await page.getByRole('button', { name: 'Use dark theme' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.screenshot({ path: '.runtime/dashboard-dark.png', fullPage: true });
  await page.getByRole('button', { name: 'Use light theme' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'Overview', exact: true }).click();
  await expect(page.getByText('Your financial overview')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const dismissToast = page.getByRole('button', { name: 'Dismiss notification' });
  if (await dismissToast.isVisible()) await dismissToast.click();
  await page.screenshot({ path: '.runtime/dashboard-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Add transaction', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  expect(errors).toEqual([]);
});

test('account registration, MongoDB-backed edits, reload and sign-in', async ({ page }) => {
  test.skip(!process.env.E2E_MONGODB_URI, 'Set E2E_MONGODB_URI to the database used by the running API');
  const email = `browser-${crypto.randomUUID()}@example.com`;
  try {
    await page.goto('/signup');
    await page.getByRole('textbox', { name: 'Your name' }).fill('Browser Tester');
    await page.getByRole('textbox', { name: 'Email address' }).fill(email);
    await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
    await page.getByLabel('Confirm password', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: 'Create my account' }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await expect(page.getByText('Private & connected')).toBeVisible();
    await expect(page.locator('.stat-card').nth(0)).toContainText('₹0');
    await page.getByRole('button', { name: 'Add transaction', exact: true }).click();
    await page.getByRole('textbox', { name: 'Description', exact: true }).fill('Real account coffee');
    await page.getByRole('spinbutton', { name: 'Amount' }).fill('200');
    await page.getByRole('dialog').getByRole('button', { name: 'Add transaction' }).click();
    await expect(page.locator('tbody')).toContainText('Real account coffee');
    await page.reload();
    await expect(page.locator('tbody')).toContainText('Real account coffee');
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await expect(page.getByText('Make this space yours.')).toBeVisible();
    await page.getByRole('navigation').getByRole('button', { name: 'Overview', exact: true }).click();
    await expect(page.locator('tbody')).not.toContainText('Real account coffee');
    await page.goto('/login');
    await page.getByRole('textbox', { name: 'Email address' }).fill(email);
    await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: 'Log in to my workspace', exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await expect(page.locator('tbody')).toContainText('Real account coffee');
  } finally {
    await mongoose.connect(process.env.E2E_MONGODB_URI!);
    const account = await mongoose.connection.collection('users').findOne({ email });
    if (account) {
      for (const name of ['transactions', 'budgets', 'goals']) await mongoose.connection.collection(name).deleteMany({ user: account._id });
      await mongoose.connection.collection('users').deleteOne({ _id: account._id, email });
    }
    await mongoose.disconnect();
  }
});
