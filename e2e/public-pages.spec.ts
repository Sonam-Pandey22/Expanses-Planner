import { test, expect } from '@playwright/test';

test('public dark mode persists through reloads, account pages, dashboard, and mobile navigation', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Use dark theme', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  expect(await page.locator('.public-site').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(24, 32, 25)');
  expect(await page.evaluate(() => localStorage.getItem('expanse-dark'))).toBe('true');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Use light theme', exact: true })).toBeVisible();
  await page.screenshot({ path: '.runtime/home-dark.png', fullPage: true });
  await page.getByRole('link', { name: 'Find your financial flow' }).click();
  await expect(page).toHaveURL(/\/signup$/);
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  expect(await page.locator('.auth-form-side').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(27, 36, 29)');
  await page.screenshot({ path: '.runtime/signup-dark.png', fullPage: true });
  await page.getByRole('link', { name: 'Log in', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Use light theme', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Explore the demo', exact: true }).click();
  await expect(page.getByText('Your financial overview')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Use light theme', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Use light theme', exact: true }).click();
  await page.getByRole('link', { name: 'Expanse home' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Use dark theme', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('button', { name: 'Open menu' }).click();
  expect(await page.locator('.public-mobile-nav').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgba(24, 32, 25, 0.96)');
  await page.getByRole('button', { name: 'Close menu' }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '.runtime/home-dark-mobile.png', fullPage: true });
  await page.goto('/login');
  await expect(page.getByRole('button', { name: 'Use light theme', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Use light theme', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Use dark theme', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('home navigation, FAQ, dedicated auth forms, readable typography and mobile layouts', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Less money stress. More life.' })).toBeVisible();
  await page.screenshot({ path: '.runtime/home-desktop.png', fullPage: true });
  await page.getByText('Do I need to connect my bank?', { exact: true }).click();
  await expect(page.getByText('No. Add transactions yourself, choose a category, and you’re ready to go. Expanse doesn’t ask for your banking credentials.')).toBeVisible();
  await page.getByRole('link', { name: 'Find your financial flow' }).click();
  await expect(page).toHaveURL(/\/signup$/);
  await expect(page.getByRole('heading', { name: 'Make yourself at home.' })).toBeVisible();
  await page.getByLabel('Your name', { exact: true }).fill('UI Tester');
  await page.getByLabel('Email address', { exact: true }).fill('tester@example.com');
  await page.getByLabel('Password', { exact: true }).fill('first-password');
  await page.getByLabel('Confirm password', { exact: true }).fill('different-password');
  await page.getByRole('button', { name: 'Create my account', exact: true }).click();
  await expect(page.locator('.auth-error[role="alert"]')).toContainText('passwords don’t match');
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text');
  await page.screenshot({ path: '.runtime/signup-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Log in', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await expect(page.getByRole('heading', { name: 'Welcome back.', exact: true })).toBeVisible();
  await page.route('**/api/auth/login', route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ error: 'Email or password is incorrect' }) }));
  await page.getByLabel('Email address', { exact: true }).fill('tester@example.com');
  await page.getByLabel('Password', { exact: true }).fill('wrong-password');
  await page.getByRole('button', { name: 'Log in to my workspace' }).click();
  await expect(page.locator('.auth-error[role="alert"]')).toHaveText('Email or password is incorrect');
  await page.screenshot({ path: '.runtime/login-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Explore the demo', exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await expect(page.getByText('Your financial overview')).toBeVisible();
  expect(await page.locator('.transaction-description strong').first().evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(14);
  await page.getByRole('link', { name: 'Expanse home' }).click();
  await expect(page).toHaveURL(/\/$/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open menu' }).click();
  await page.getByRole('navigation', { name: 'Mobile site navigation' }).getByRole('link', { name: 'Why Expanse' }).click();
  await expect(page.getByRole('button', { name: 'Open menu' })).toHaveAttribute('aria-expanded', 'false');
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '.runtime/home-mobile.png', fullPage: true });
  for (const path of ['/login', '/signup']) {
    await page.goto(path);
    await expect(page.getByLabel('Email address', { exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(await page.getByLabel('Email address').evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(16);
    await page.screenshot({ path: `.runtime/${path.slice(1)}-mobile.png`, fullPage: true });
  }
  expect(errors).toEqual([]);
});
